-- =====================================================================
--  Лабораторна 2 (NoSQL): SQL-реалізація тих самих даних, що в Redis
--  СУБД: PostgreSQL 14+
--
--  Відповідність структурам Redis (див. docs у звіті):
--    cart:{user}:{store}  (HASH offer -> qty)   <=>  carts + cart_items   (2 таблиці)
--    offer:{id}           (HASH name,price)     <=>  offers
--    views:{day}:{store}  (ZSET offer -> views) <=>  offer_views_daily
--
--  Це "вузький зріз" схеми з лабораторної 1 (carts, cart_items, store_products+products):
--  таблиці users/stores прибрано, щоб тест вимірював саме кошики й лічильники,
--  а не вартість перевірки сторонніх зовнішніх ключів.
-- =====================================================================
DROP TABLE IF EXISTS offer_views_daily, cart_items, carts, offers CASCADE;

CREATE TABLE offers (
    id        integer       PRIMARY KEY,
    store_id  integer       NOT NULL,
    name      text          NOT NULL,
    price     numeric(12,2) NOT NULL CHECK (price >= 0)
);

CREATE TABLE carts (
    id         bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer     NOT NULL,
    store_id   integer     NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_carts_user_store UNIQUE (user_id, store_id)      -- один кошик на магазин
);

CREATE TABLE cart_items (
    cart_id  bigint  NOT NULL REFERENCES carts(id) ON DELETE CASCADE,
    offer_id integer NOT NULL REFERENCES offers(id),
    quantity integer NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (cart_id, offer_id)
);

CREATE TABLE offer_views_daily (
    day      date    NOT NULL,
    store_id integer NOT NULL,
    offer_id integer NOT NULL REFERENCES offers(id),
    views    bigint  NOT NULL CHECK (views >= 0),
    PRIMARY KEY (day, store_id, offer_id)
);
