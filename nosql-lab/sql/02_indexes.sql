-- Індекс для запиту "топ-N товарів магазину за день" (створюється після завантаження даних).
-- Без нього top-N читає всі ~2000 рядків магазину з первинного ключа й сортує їх;
-- з ним - читає 10 рядків, але кожне збільшення лічильника стає повільнішим
-- (оновлення індексованого стовпця views не може бути "HOT-оновленням").
CREATE INDEX ix_views_top ON offer_views_daily (day, store_id, views DESC);
CREATE INDEX ix_offers_store ON offers (store_id);
